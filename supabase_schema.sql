-- ============================================================
-- Supabase Schema for MiniShop: signup & login tables
-- ============================================================

-- 1. public.signup jadvali
create table if not exists public.signup (
    id bigint generated by default as identity primary key,
    username text not null,
    login text not null unique,
    password text not null,
    created_at timestamptz not null default now()
);

-- RLS yoqish
alter table public.signup enable row level security;

-- Anon va authenticated foydalanuvchilar uchun SELECT ruxsati
create policy "Allow select on signup for all" on public.signup
    for select
    to anon, authenticated
    using (true);

-- Anon va authenticated foydalanuvchilar uchun INSERT ruxsati
create policy "Allow insert on signup for all" on public.signup
    for insert
    to anon, authenticated
    with check (true);


-- 2. public.login jadvali
create table if not exists public.login (
    id bigint generated by default as identity primary key,
    login text not null,
    password text not null,
    status text not null,
    created_at timestamptz not null default now()
);

-- RLS yoqish
alter table public.login enable row level security;

-- Anon va authenticated foydalanuvchilar uchun SELECT ruxsati
create policy "Allow select on login for all" on public.login
    for select
    to anon, authenticated
    using (true);

-- Anon va authenticated foydalanuvchilar uchun INSERT ruxsati
create policy "Allow insert on login for all" on public.login
    for insert
    to anon, authenticated
    with check (true);
